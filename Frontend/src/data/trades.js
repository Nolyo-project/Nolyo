export const TRADE_LIST = Object.values(TRADES)

export function pluralLabel(word, count) {
  if (count <= 1) return word
  if (word === 'rendez-vous') return word
  return `${word}s`
}

export function copyForTrade(tradeId) {
  const copy = TRADES[tradeId] || TRADES.other
  return { quoteCta: 'Demander un devis', ...copy }
}

export function copyForUser(user) {
  const copy = copyForTrade(user?.onboarding?.trade)
  if (user?.onboarding?.trade === 'other' && user?.onboarding?.tradeLabel) {
    return { ...copy, label: user.onboarding.tradeLabel }
  }
  return copy
}

